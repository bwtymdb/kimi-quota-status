import { readFile, writeFile } from 'node:fs/promises'

const names = ['./remote-contract.cjs', './client-main.cjs']
const sources = await Promise.all(names.map(async name => [name, await readFile(new URL(name, import.meta.url), 'utf8')]))
const wrappers = sources.map(([name, source]) => `    ${JSON.stringify(name)}: function(module, exports, require) {\n${source}\n    },`).join('\n')
const artifact = `// Generated by build.mjs. Do not edit.
window.__ModuleLoader__.load({
  id: '@bwtymdb/kimi-quota-status',
  factory(require) {
    const modules = {
${wrappers}
    }
    const cache = Object.create(null)
    function localRequire(id) {
      if (!id.startsWith('.')) return require(id)
      if (cache[id] !== undefined) return cache[id].exports
      const factory = modules[id]
      if (factory === undefined) throw new Error('Unknown local module: ' + id)
      const module = { exports: {} }
      cache[id] = module
      factory(module, module.exports, localRequire)
      return module.exports
    }
    return localRequire('./client-main.cjs')
  },
})
`
await writeFile(new URL('./client.js', import.meta.url), artifact, 'utf8')
